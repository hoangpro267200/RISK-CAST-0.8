def sha256_file(p: Path) -> str:
    h = hashlib.sha256()
    with p.open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def download_scc_binary(dest: Path) -> Optional[Path]:
    """
    Attempt to download scc from GitHub releases.
    We fetch the latest tag page (static 'latest') and then use a conservative filename strategy.
    If the pattern isn't found, we skip.
    """
    latest_url = "https://github.com/boyter/scc/releases/latest"
    try:
        with urllib.request.urlopen(latest_url, timeout=20) as resp:
            html = resp.read().decode("utf-8", errors="ignore")
    except Exception:
        return None

    sysname = platform.system().lower()
    machine = platform.machine().lower()

    if sysname.startswith("win"):
        os_token = "windows"
        ext = ".zip"
    elif sysname == "darwin":
        os_token = "darwin"
        ext = ".tar.gz"
    else:
        os_token = "linux"
        ext = ".tar.gz"

    if machine in ("x86_64", "amd64"):
        arch_token = "amd64"
    elif machine in ("aarch64", "arm64"):
        arch_token = "arm64"
    else:
        return None

    # Look for an asset link containing both tokens.
    # Example expected patterns include: scc_..._<os>_<arch>.tar.gz or scc-...-<os>-<arch>.zip
    rx = re.compile(r'href=\"(?P<href>/boyter/scc/releases/download/[^\\\"]+%s[^\\\"]*%s[^\\\"]*%s)\"' % (os_token, arch_token, re.escape(ext)))
    m = rx.search(html)
    if not m:
        # fallback: allow either order
        rx2 = re.compile(r'href=\"(?P<href>/boyter/scc/releases/download/[^\\\"]+%s[^\\\"]*%s[^\\\"]*%s)\"' % (arch_token, os_token, re.escape(ext)))
        m = rx2.search(html)
        if not m:
            return None

    asset_path = m.group("href").replace("&amp;", "&")
    asset_url = "https://github.com" + asset_path

    dest.parent.mkdir(parents=True, exist_ok=True)
    try:
        with urllib.request.urlopen(asset_url, timeout=60) as resp, dest.open("wb") as f:
            shutil.copyfileobj(resp, f)
    except Exception:
        return None
    return dest


def extract_scc(archive: Path, workdir: Path) -> Optional[Path]:
    sysname = platform.system().lower()
    try:
        if sysname.startswith("win"):
            import zipfile

            with zipfile.ZipFile(archive, "r") as z:
                z.extractall(workdir)
        else:
            import tarfile

            with tarfile.open(archive, "r:gz") as t:
                t.extractall(workdir)
    except Exception:
        return None

    # Find executable named scc or scc.exe
    for p in workdir.rglob("*"):
        if p.is_file() and p.name in ("scc", "scc.exe"):
            if not sysname.startswith("win"):
                p.chmod(p.stat().st_mode | stat.S_IXUSR)
            return p
    return None


def run_scc(repo_root: Path) -> Optional[dict]:
    scc = shutil.which("scc")
    if scc:
        try:
            out = subprocess.check_output([scc, "--format", "json", str(repo_root)], text=True)
            return {"tool": "scc", "raw_json": out}
        except Exception:
            return None

    # Attempt download
    with tempfile.TemporaryDirectory() as td:
        td_path = Path(td)
        archive = td_path / "scc_download"
        downloaded = download_scc_binary(archive)
        if not downloaded:
            return None
        extracted = extract_scc(downloaded, td_path / "extracted")
        if not extracted:
            return None
        try:
            out = subprocess.check_output([str(extracted), "--format", "json", str(repo_root)], text=True)
            return {
                "tool": "scc(downloaded)",
                "raw_json": out,
                "archive_sha256": sha256_file(downloaded),
            }
        except Exception:
            return None


