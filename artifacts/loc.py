@dataclass(frozen=True)
class FileStats:
    path: str
    language: str
    code_lines: int
    comment_lines: int
    blank_lines: int
    total_lines: int


def should_exclude_path(path: Path, repo_root: Path) -> bool:
    rel = path.relative_to(repo_root)

    for part in rel.parts:
        if part in EXCLUDE_DIRS:
            return True

    if path.name in EXCLUDE_FILE_NAMES:
        return True

    if path.suffix.lower() in EXCLUDE_EXTENSIONS:
        return True

    rel_s = str(rel).replace("\\", "/")
    for rx in EXCLUDE_GLOBS_RE:
        if rx.match(rel_s):
            return True

    return False


def read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8", errors="ignore")


def count_file(path: Path, lang: str, repo_root: Path) -> List[FileStats]:
    text = read_text(path)

    # Migrations rule: exclude only if reliably auto-generated.
    if is_reliably_autogenerated_migration(path, text):
        return []

    # Otherwise: include migrations, but with separate bucket "migrations"
    lang_bucket = lang
    if is_migration_file(path):
        lang_bucket = "migrations"

    if lang == "Python":
        c, cm, b = count_python(text)
        return [FileStats(str(path.relative_to(repo_root)), lang_bucket, c, cm, b, c + cm + b)]

    if lang in ("JavaScript", "TypeScript", "TSX", "HTML", "CSS", "SQL", "Dockerfile"):
        if lang == "SQL":
            c, cm, b = count_c_like(text, line_comment="--")
        elif lang == "CSS":
            c, cm, b = count_c_like(text, line_comment="/*")
        elif lang == "HTML":
            c, cm, b = count_c_like(text, line_comment="<!--")
        else:
            c, cm, b = count_c_like(text, line_comment="//")
        return [FileStats(str(path.relative_to(repo_root)), lang_bucket, c, cm, b, c + cm + b)]

    if lang == "YAML":
        c, cm, b = count_yaml(text)
        return [FileStats(str(path.relative_to(repo_root)), lang_bucket, c, cm, b, c + cm + b)]

    if lang == "Markdown":
        c, cm, b = count_markdown(text)
        # report separately as docs (not code)
        return [FileStats(str(path.relative_to(repo_root)), "docs", c, cm, b, c + cm + b)]

    if lang == "Vue":
        out: List[FileStats] = []
        for sublang, (c, cm, b) in count_vue(text).items():
            out.append(
                FileStats(str(path.relative_to(repo_root)), f"{lang_bucket}:{sublang.split(':')[-1]}", c, cm, b, c + cm + b)
            )
        return out

    return []


def aggregate(file_stats: List[FileStats]) -> Dict[str, Dict[str, int]]:
    agg: Dict[str, Dict[str, int]] = {}
    for s in file_stats:
        if s.language not in agg:
            agg[s.language] = {"code_lines": 0, "comment_lines": 0, "blank_lines": 0, "files_count": 0, "total_lines": 0}
        agg[s.language]["code_lines"] += s.code_lines
        agg[s.language]["comment_lines"] += s.comment_lines
        agg[s.language]["blank_lines"] += s.blank_lines
        agg[s.language]["total_lines"] += s.total_lines
        agg[s.language]["files_count"] += 1
    return agg


def stable_walk_files(repo_root: Path) -> Iterable[Path]:
    # Deterministic traversal: sort directories and files lexicographically.
    for dirpath, dirnames, filenames in os.walk(repo_root):
        dirnames.sort()
        filenames.sort()
        base = Path(dirpath)
        for fn in filenames:
            yield base / fn


