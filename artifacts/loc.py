LANGUAGE_BY_EXT = {
    ".py": "Python",
    ".ts": "TypeScript",
    ".tsx": "TSX",
    ".js": "JavaScript",
    ".mjs": "JavaScript",
    ".cjs": "JavaScript",
    ".vue": "Vue",
    ".html": "HTML",
    ".htm": "HTML",
    ".css": "CSS",
    ".scss": "CSS",
    ".sass": "CSS",
    ".less": "CSS",
    ".sql": "SQL",
    ".yml": "YAML",
    ".yaml": "YAML",
    ".md": "Markdown",
    ".markdown": "Markdown",
}


def detect_language(path: Path) -> Optional[str]:
    name = path.name
    if name == "Dockerfile":
        return "Dockerfile"
    ext = path.suffix.lower()
    return LANGUAGE_BY_EXT.get(ext)


def is_docs_language(lang: str) -> bool:
    return lang == "Markdown"


def is_migration_file(path: Path) -> bool:
    # Common patterns: alembic migrations under migrations/versions/*.py etc.
    parts = [p.lower() for p in path.parts]
    if "migrations" in parts or "alembic" in parts:
        return True
    # Django migrations convention
    if any(p == "migrations" for p in parts) and path.suffix.lower() == ".py":
        return True
    return False


AUTO_GENERATED_MARKERS_RE = re.compile(
    r"(auto-?generated|generated by|this file is generated|do not edit|autogenerated)",
    re.IGNORECASE,
)


def is_reliably_autogenerated_migration(path: Path, content: str) -> bool:
    """
    Only exclude migrations if we can detect reliably they are auto-generated.
    Heuristic: contains strong "generated/do not edit" markers near the top.
    """
    if not is_migration_file(path):
        return False
    head = "\n".join(content.splitlines()[:50])
    return bool(AUTO_GENERATED_MARKERS_RE.search(head))


# =============================================================================
# LINE CLASSIFICATION
# =============================================================================

TRIPLE_QUOTE_RE = re.compile(r"(^|[^\\])('''|\"\"\")")


def _split_lines_newline_counting(text: str) -> List[str]:
    # Standard LOC: newline separators.
    # splitlines() would drop the trailing empty line; using split("\n") matches the earlier behavior.
    return text.split("\n")


def count_python(text: str) -> Tuple[int, int, int]:
    """
    Python rules:
      - line starting with # (after whitespace) is a comment
      - docstrings counted as comments only if standalone triple-quoted blocks not assigned to variables
    Notes:
      This is a lightweight state machine; it won't perfectly parse Python but is deterministic.
    """
    code = comment = blank = 0
    in_doc = False
    doc_delim: Optional[str] = None

    for line in _split_lines_newline_counting(text):
        raw = line
        s = raw.strip()
        if s == "":
            blank += 1
            continue

        # docstring block handling
        if in_doc:
            comment += 1
            if doc_delim and doc_delim in raw:
                # close if odd count on this line
                if raw.count(doc_delim) % 2 == 1:
                    in_doc = False
                    doc_delim = None
            continue

        ws = raw.lstrip()
        if ws.startswith("#"):
            comment += 1
            continue

        # detect standalone docstring start:
        # - must start with triple quote after whitespace
        # - must NOT look like assignment: x = """..."""
        if ws.startswith('"""') or ws.startswith("'''"):
            # If it's on a line that also contains an assignment before it, don't treat as docstring.
            # (we already used lstrip so this excludes leading whitespace; assignment would be in ws)
            if "=" not in ws.split(ws[:3])[0]:
                comment += 1
                delim = ws[:3]
                # single-line docstring """foo"""
                if ws.count(delim) >= 2 and ws.count(delim) % 2 == 0:
                    in_doc = False
                    doc_delim = None
                else:
                    in_doc = True
                    doc_delim = delim
                continue

        code += 1

    return code, comment, blank


def count_c_like(text: str, line_comment: str = "//") -> Tuple[int, int, int]:
    code = comment = blank = 0
    in_block = False
    for line in _split_lines_newline_counting(text):
        s = line.strip()
        if s == "":
            blank += 1
            continue

        if in_block:
            comment += 1
            if "*/" in line:
                in_block = False
            continue

        if s.startswith(line_comment):
            comment += 1
            continue

        if "/*" in line:
            comment += 1
            if "*/" not in line or (line.find("/*") > line.find("*/")):
                in_block = True
            continue

        code += 1
    return code, comment, blank


def count_yaml(text: str) -> Tuple[int, int, int]:
    code = comment = blank = 0
    for line in _split_lines_newline_counting(text):
        if line.strip() == "":
            blank += 1
            continue
        if line.lstrip().startswith("#"):
            comment += 1
        else:
            code += 1
    return code, comment, blank


def count_markdown(text: str) -> Tuple[int, int, int]:
    # For reporting: docs bucket, no comment parsing.
    code = comment = blank = 0
    for line in _split_lines_newline_counting(text):
        if line.strip() == "":
            blank += 1
        else:
            code += 1
    return code, comment, blank


VUE_BLOCK_RE = re.compile(r"<(?P<tag>template|script|style)(?P<attrs>[^>]*)>(?P<body>.*?)</\1>", re.I | re.S)


def count_vue(text: str) -> Dict[str, Tuple[int, int, int]]:
    """
    Vue SFC: count <template>, <script>, <style> separately and tag them:
      - Vue:template
      - Vue:script
      - Vue:style
    """
    counts: Dict[str, Tuple[int, int, int]] = {}
    for m in VUE_BLOCK_RE.finditer(text):
        tag = m.group("tag").lower()
        body = m.group("body") or ""
        if tag == "script":
            counts["Vue:script"] = count_c_like(body, line_comment="//")
        elif tag == "template":
            # HTML comments <!-- --> are treated as comments; simplified as code-only here to avoid overcounting
            counts["Vue:template"] = count_c_like(body, line_comment="<!--")  # pragmatic approximation
        elif tag == "style":
            counts["Vue:style"] = count_c_like(body, line_comment="/*")  # will be handled by block logic
    if not counts:
        counts["Vue"] = count_c_like(text, line_comment="//")
    return counts


