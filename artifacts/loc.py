def write_reports(artifacts_dir: Path, file_stats: List[FileStats], agg: Dict[str, Dict[str, int]]) -> Tuple[Path, Path, dict]:
    artifacts_dir.mkdir(parents=True, exist_ok=True)
    csv_path = artifacts_dir / "loc_report.csv"
    json_path = artifacts_dir / "loc_report.json"

    total_code = sum(s.code_lines for s in file_stats)
    total_comment = sum(s.comment_lines for s in file_stats)
    total_blank = sum(s.blank_lines for s in file_stats)

    by_lang_rows = [
        {
            "language": lang,
            **vals,
        }
        for lang, vals in agg.items()
    ]
    by_lang_rows.sort(key=lambda r: (-r["code_lines"], r["language"]))

    top_files = sorted(file_stats, key=lambda s: (-s.code_lines, s.path))[:50]

    report = {
        "summary": {
            "total_code_lines": total_code,
            "total_comment_lines": total_comment,
            "total_blank_lines": total_blank,
            "total_lines": total_code + total_comment + total_blank,
            "total_files": len(file_stats),
        },
        "by_language": by_lang_rows,
        "top_50_files": [
            {
                "path": s.path,
                "language": s.language,
                "code_lines": s.code_lines,
                "comment_lines": s.comment_lines,
                "blank_lines": s.blank_lines,
                "total_lines": s.total_lines,
            }
            for s in top_files
        ],
    }

    json_path.write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    with csv_path.open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["Language", "code_lines", "comment_lines", "blank_lines", "total_lines", "files_count"])
        for r in by_lang_rows:
            w.writerow([r["language"], r["code_lines"], r["comment_lines"], r["blank_lines"], r["total_lines"], r["files_count"]])
        w.writerow([])
        w.writerow(["Top 50 largest files by code_lines"])
        w.writerow(["path", "language", "code_lines", "comment_lines", "blank_lines", "total_lines"])
        for s in top_files:
            w.writerow([s.path, s.language, s.code_lines, s.comment_lines, s.blank_lines, s.total_lines])

    return json_path, csv_path, report


def print_summary(report: dict, cross: Optional[dict]) -> None:
    s = report["summary"]
    print("=" * 80)
    print("LOC REPORT")
    print("=" * 80)
    print(f"Total LOC (code):     {s['total_code_lines']:,}")
    print(f"Total comment lines:  {s['total_comment_lines']:,}")
    print(f"Total blank lines:    {s['total_blank_lines']:,}")
    print(f"Total lines:          {s['total_lines']:,}")
    print(f"Files counted:        {s['total_files']:,}")
    print()
    print(f"{'Language':<22} {'code':>12} {'comment':>12} {'blank':>12} {'total':>12} {'files':>8}")
    print("-" * 80)
    for r in report["by_language"]:
        print(
            f"{r['language']:<22} {r['code_lines']:>12,} {r['comment_lines']:>12,} {r['blank_lines']:>12,} {r['total_lines']:>12,} {r['files_count']:>8,}"
        )
    print()

    if cross:
        print("Cross-check:")
        print(f"  tool: {cross.get('tool')}")
        if cross.get("archive_sha256"):
            print(f"  downloaded archive sha256: {cross['archive_sha256']}")
    else:
        print("Cross-check: skipped (scc not found and download unavailable)")


def main() -> int:
    repo_root = Path.cwd().resolve()
    artifacts_dir = repo_root / "artifacts"

    file_stats: List[FileStats] = []

    for path in stable_walk_files(repo_root):
        if not path.is_file():
            continue
        if should_exclude_path(path, repo_root):
            continue

        lang = detect_language(path)
        if not lang:
            continue

        # Never count artifacts outputs themselves
        if str(path.relative_to(repo_root)).replace("\\", "/").startswith("artifacts/"):
            continue

        file_stats.extend(count_file(path, lang, repo_root))

    agg = aggregate(file_stats)
    json_path, csv_path, report = write_reports(artifacts_dir, file_stats, agg)

    cross = run_scc(repo_root)
    # If we have scc output, try to compare code total (best-effort).
    if cross and "raw_json" in cross:
        try:
            scc_data = json.loads(cross["raw_json"])
            # scc JSON formats can vary; best effort: sum over language entries if present.
            scc_code = None
            if isinstance(scc_data, dict) and "languageSummary" in scc_data:
                scc_code = sum(int(x.get("Code", 0)) for x in scc_data["languageSummary"])
            if scc_code is not None:
                ours = report["summary"]["total_code_lines"]
                diff_pct = abs(scc_code - ours) / max(scc_code, ours) * 100 if max(scc_code, ours) else 0.0
                cross["scc_total_code_lines"] = scc_code
                cross["ours_total_code_lines"] = ours
                cross["diff_pct"] = diff_pct
                if diff_pct > 2.0:
                    cross["explanation"] = (
                        "Difference >2% likely due to: docstring classification, Vue sub-bucketing, "
                        "migration bucketing, or different ignore semantics."
                    )
        except Exception:
            pass

    # Re-write JSON to include cross-check metadata (still under artifacts/)
    report["cross_check"] = cross
    json_path.write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    print_summary(report, cross)
    print()
    print(f"Wrote: {json_path}")
    print(f"Wrote: {csv_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
